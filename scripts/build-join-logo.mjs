import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const logoPath = join(__dirname, '../images/logo.png');
const outputPath = join(__dirname, '../src/server/routes/joinPageLogo.ts');

const logoBytes = readFileSync(logoPath);
const dataUri = `data:image/png;base64,${logoBytes.toString('base64')}`;

const contents = `/**
 * Base64 data URI for the Team Hub logo used by the public join landing page.
 *
 * Generated by \`scripts/build-join-logo.mjs\`. Do not edit by hand.
 */
export const JOIN_PAGE_LOGO_DATA_URI = ${JSON.stringify(dataUri)};
`;

writeFileSync(outputPath, contents, 'utf8');
execSync(`pnpm exec prettier --write ${JSON.stringify(outputPath)}`, {
  cwd: join(__dirname, '..'),
  stdio: 'inherit'
});
console.log(`Wrote ${outputPath}`);
